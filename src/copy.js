// 渲染层引号：ASCII 双引号成对替换为「」（不配对的原样保留，不用状态机 toggle）；
// 全角 “ ” 一并归一为「」。卡面与结果页共用同一实现。results.json 原文不改。
export function toCorner(s) {
  return String(s)
    .replace(/"([^"]*)"/g, "「$1」")
    .replace(/“/g, "「")
    .replace(/”/g, "」");
}

// value(0-100) → 该档判词；越界钳制到 [0,100]
export function pickVerdict(kind, value) {
  const list = VERDICTS[kind] || [];
  const v = Math.max(0, Math.min(100, Math.round(Number(value) || 0)));
  const hit = list.find((b) => v >= b.min && v <= b.max);
  return hit ? hit.text : "";
}
